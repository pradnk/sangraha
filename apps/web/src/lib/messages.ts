export type MessageKey = keyof (typeof MESSAGES)['en'];

/** Looks up a product string, falling back to English for untranslated locales. */
/**
 * Whether a string is one of our message keys.
 *
 * Used where a value might be a key or might already be words — a field type's
 * validation failure, for instance, which is a key for the ones we define and
 * a plain sentence for anything Zod produced itself.
 */
export function isMessageKey(value: string): value is MessageKey {
  return Object.hasOwn(MESSAGES.en, value);
}

export function m(locale: string, key: MessageKey, vars?: Record<string, string | number>): string {
  const catalogue = MESSAGES[locale as keyof typeof MESSAGES] ?? MESSAGES.en;
  let value: string = catalogue[key] ?? MESSAGES.en[key];
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}
